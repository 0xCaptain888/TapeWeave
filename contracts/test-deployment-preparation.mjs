import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {prepareDeployment} from './prepare-deployment.mjs';
const tools = process.env.TAPEWEAVE_SOLIDITY_TOOLS;
const {ethers} = createRequire(`${tools}/package.json`)('ethers');
const a = await prepareDeployment(tools);
const b = await prepareDeployment(tools);
assert.deepEqual(a,b);
assert.equal(a.ready_to_send,false);
assert.equal(a.broadcast,false);
assert.equal(a.simulated,false);
assert.equal(a.wallet_creation_adapter,null);
assert.equal(a.account_address,null);
assert.equal(a.initcode,a.creation_bytecode+a.constructor_args.slice(2));
const decoded = ethers.AbiCoder.defaultAbiCoder().decode(['address','bytes32','bytes32'],a.constructor_args);
assert.equal(decoded[0],a.processor);
assert.equal(decoded[1],a.pulse_hash);
assert.equal(decoded[2],a.alternating_hash);
assert.notEqual(a.pulse_hash,a.alternating_hash);
assert.ok(Object.keys(a.immutable_references).length > 0);
assert.ok(a.initcode.length > a.constructor_args.length);
await assert.rejects(() => prepareDeployment('relative'));
console.log('PASS: deterministic offline initcode; constructor order/hash; immutable warnings; no send-ready claims');
